// ---- timing, copied from emu/main.cpp -------------------------------------
static constexpr uint32_t kCpuClock = 96000000u;             // MAME GPCE4 clock
// How much guest time one *rendered* frame covers.  This is independent of how
// fast the emulator is: game speed is guest-cycles-per-wall-second, which is
// host throughput, so halving this only makes us render twice as often for the
// same amount of guest progress.  In heavy redraw the guest saturates whatever
// budget it is given, so a smaller budget means more, shorter frames at the
// same game speed - that is what the "large-area movement is choppy" report
// responds to.  /120 = 800,000 cycles = 1/120 s of guest time per frame.
static uint32_t s_frame_cycles = kCpuClock / 60u;            // live: F <hz>
// 16 kHz rather than the guest's 20 kHz timer_a period: 48,000 guest cycles
// (= 48,000 instructions in the worst case) measured up to 28 ms of wall clock
// in a cold AOT scene, so a single slice could blow through the whole frame
// budget before the guard ever ran.  Slices this short keep the worst case
// under ~10 ms and still cover four timer_a periods exactly.
static constexpr uint32_t kSliceCycles = 48000u;

