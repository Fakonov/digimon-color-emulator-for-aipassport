//  app_main.cpp - the Digimon Color (GPCE4) firmware booted on the AI Passport
//
//  This is the C3 counterpart of emu/main.cpp.  It runs the same MAME 0.289
//  unSP 2.0 interpreter (main/emu/isa/*, ported verbatim), the same GPCE4 SoC
//  model (main/emu/gpce4.cpp) and the same ST7735 controller model
//  (main/emu/st7735.cpp), with two device-side substitutions:
//
//    * the 8 MiB SPI flash image is a sparse page store in the `roms`
//      partition, read through SparseRom's 64 KiB page cache (emu/romstore.h)
//    * the internal 64 KiB mask ROM is embedded in the app image
//      (target_add_binary_data, symbol `internal_rom`)
//
//  Nothing is real time.  One guest frame is 1,600,000 guest cycles (96 MHz /
//  60 Hz) - about 1 M guest instructions - and the interpreter needs roughly
//  0.15-0.25 s for that on a 160 MHz C3, so the panel updates at 4-7 fps.  The
//  point is that the original ROM boots, runs its own renderer and shows the
//  game's 96x96 screen on the panel; see docs/C3_PORT.md.
// ---------------------------------------------------------------------------
