// The AI Passport panel is not inverted after all: the first build used 180 deg
// and the picture came out upside down, so the guest window is written straight
// through.  Change to 1/2/3 only if the panel mount changes (compile time on
// purpose - the three keys are guest input, not a settings UI).
static constexpr int kRot = 0;

// ---------------------------------------------------------------------------
//  panel output
// ---------------------------------------------------------------------------
static inline void rot_map(int x, int y, int *sx, int *sy)
{
    switch (kRot & 3) {
    case 0:
        *sx = x;
        *sy = y;
        break;
    case 1:  // 90 deg clockwise
        *sx = y;
        *sy = kWinH - 1 - x;
        break;
    case 2:  // 180 (the first build used this; the picture was upside down)
        *sx = kWinW - 1 - x;
        *sy = kWinH - 1 - y;
        break;
    case 4:  // mirror on the horizontal axis only
        *sx = x;
        *sy = kWinH - 1 - y;
        break;
    case 5:  // mirror on the vertical axis only
        *sx = kWinW - 1 - x;
        *sy = y;
        break;
    default:  // 270 deg clockwise
        *sx = kWinW - 1 - y;
        *sy = x;
        break;
    }
}

// True once the guest has drawn something into the visible window.
static bool window_has_content(void)
{
    const uint16_t *fb = s_soc.lcd.fb;
    for (int y = 0; y < kWinH; y++) {
        const uint16_t *row = fb + (kWinY + y) * kFbPanel + kWinX;
        for (int x = 0; x < kWinW; x++) {
            if (row[x])
                return true;
        }
    }
    return false;
}

// Push the 96x96 guest window to the panel.
//
// Three things matter here, in order of how much time they used to cost:
//
//   * bytes on the wire - the window is 192x192 on a 320x240 panel, so the old
//     code spent 40% of every transfer on letterbox that never changes.  Now
//     only the 192-wide window is addressed.
//   * unchanged rows    - the panel keeps its content, so a strip whose source
//     rows did not change is skipped entirely.  Menus and the clock repaint a
//     few rows per frame, not all 192.
//   * per-pixel work    - kRot == 0 makes the mapping an identity copy with 2x
//     horizontal expansion, which is one 32-bit store per two pixels.
// One-off full-panel fill.  The per-frame blit only touches the 192x192 window,
// so the surround has to be painted once or the panel shows its power-on GRAM.
static void panel_fill_black(void)
{
    // 320 pixels wide * kChunkRows rows * 2 bytes.  This used to be its own
    // static 10 KiB buffer; s_strip is the larger 15 KiB scratch every other
    // panel painter already shares, and the fill only runs once at boot before
    // anything else has touched it, so it borrows that instead of holding a
    // second full-panel buffer in DRAM for the life of the firmware.
    static_assert(kStripBytes >= 320 * kChunkRows * 2,
                  "s_strip must hold one full-width fill chunk");
    uint8_t *fill = s_strip;
    if (!s_display_ok)
        return;
    memset(fill, 0, 320 * kChunkRows * 2);
    for (int y = 0; y < 240; y += kChunkRows) {
        const int rows = (y + kChunkRows <= 240) ? kChunkRows : (240 - y);
        if (display_draw_bitmap(0, y, 320, rows, fill) != ESP_OK) {
            ESP_LOGE(TAG, "panel fill failed at y=%d", y);
            return;
        }
    }
    ESP_LOGI(TAG, "panel cleared to black (320x240)");
}

// The four-band clear that used to live here is gone: the wall in
// panel_draw_bezel() covers exactly the same region and is what belongs there
// now.  Its history is worth keeping though, because the same trap is one
// layout change away:
//
// The clear used to touch two vertical bands only, which was correct while the
// window was 256x224 at (32,8): the settings card is 300x212 at (10,16), so it
// sat entirely inside the window vertically and the next blit covered its top
// and bottom.  Once the window shrank to 192x192 at (64,24) the card stuck out
// 8 rows above it (16..23) and 12 rows below it (216..227) - two horizontal
// strips nothing repainted, which is the "settings elements left above and
// below the game" the owner reported.

// The wall, the metal rim, the well, the 30 px corner mask and the battery
// readout all live in bezel.cpp now.  It replaced four painters that used to sit
// here: brick_px()/panel_brick_band() (a 28x11 procedural grid that read as
// printed mosaic), panel_draw_battery() (5x7 ink on a black box) and
// panel_draw_bezel() (four bands of wall, no rim at all).
//
// The rule that survived the move: blit_frame() only pushes dirty tiles inside
// the 192x192 window, so every pixel outside it needs someone else to repaint
// it.  bezel_paint() is that someone, and it writes the glass black on purpose -
// the caller must set s_blit_repaint_all so the picture returns in the same
// frame the settings card closes.

static void blit_frame(void)
{
    const uint16_t *fb = s_soc.lcd.fb;
    // Dirty tracking is per 16x16 tile and the output is sent one tile row at a
    // time.  A minimum bounding box was worse than the old row scan: the clock
    // ticks in the top-left tile and the sprite moves in the middle, so the box
    // covered the whole window on every frame (blit_pct 78, fps 39).  Per band
    // the burst is only as wide as the tiles that actually changed.
    //
    // kBlitEvery throttles how often a dirty band is committed.  The tiles stay
    // dirty until the frame that actually sends them, so nothing is lost: at 2
    // the moving parts update at 30 Hz while a still picture still costs zero.
    static constexpr int kTile = 16;
    static constexpr int kTilesX = kWinW / kTile;
    static constexpr int kTilesY = kWinH / kTile;
    static bool s_have_prev = false;
    static uint32_t s_idle_frames = 0;
    static uint32_t s_phase = 0;

    if (s_blit_repaint_all) {
        s_blit_repaint_all = false;
        s_have_prev = false;
    }

    // Which tiles changed is recorded by the LCD model, not rediscovered here.
    // Every pixel the guest pushes lands in fb[] through St7735::store_pixel or
    // fill_run, and those two mark a bit for the 16x16 tile they touched.  The
    // scan that used to live here hashed all 9,216 visible pixels per host frame
    // (36 tiles x 256 px of FNV) - about 50k host cycles whether or not the
    // picture moved, which on a parked handset was pure heat.
    //
    // Window tile (ty,tx) covers GRAM rows kWinY+ty*16 .. +15 and columns
    // tx*16..+15.  kWinY is 18, so a window tile straddles GRAM tile rows ty+1
    // and ty+2, and column tx maps straight through.  96/16 = 6 tiles wide, and
    // the 128-wide GRAM tile row is masked down to those six columns.
    uint8_t rowmask[kTilesY];
    bool any = false;
    for (int ty = 0; ty < kTilesY; ty++) {
        const uint8_t m = uint8_t(s_soc.lcd.m_dirty[ty + 1] | s_soc.lcd.m_dirty[ty + 2]);
        rowmask[ty] = uint8_t(m & ((1u << kTilesX) - 1u));
        if (rowmask[ty])
            any = true;
    }
    if (!s_have_prev) {
        for (int ty = 0; ty < kTilesY; ty++)
            rowmask[ty] = uint8_t((1u << kTilesX) - 1u);
        any = true;
    }

    bool dirty[kTilesY][kTilesX];
    for (int ty = 0; ty < kTilesY; ty++)
        for (int tx = 0; tx < kTilesX; tx++)
            dirty[ty][tx] = (rowmask[ty] >> tx) & 1u;

    // Idle repair sweep, one band per frame.  It used to push all six bands in
    // one frame: 6 x 12,288 B = 11-15 ms of blocking SPI landing on a single
    // frame every 120 idle frames (~2 s at 57 fps, ~6 s at 19 fps).  On a still
    // picture that was the only periodic hitch the display path contributed.
    // Spreading it over six frames changes nothing semantically - the picture
    // is static, which is why the sweep started - and no frame pays more than
    // one band.
    static int s_repair_ty = -1;
    if (s_repair_ty >= 0) {
        for (int tx = 0; tx < kTilesX; tx++)
            dirty[s_repair_ty][tx] = true;
        any = true;
    } else if (!any) {
        if (++s_idle_frames < 120) return;
        s_idle_frames = 0;
        s_repair_ty = 0;
        for (int tx = 0; tx < kTilesX; tx++)
            dirty[0][tx] = true;
        any = true;
    } else {
        s_idle_frames = 0;
        // Throttled frame: leave the dirty bits alone so the same tiles are
        // still dirty next frame; St7735::dirty_clear() only runs after a band
        // actually reached the panel.
        if (s_blit_every > 1 && (++s_phase % (uint32_t)s_blit_every) != 0) return;
    }

    // How much of the window is dirty decides which transfer shape is cheaper.
    int ntiles = 0;
    for (int ty = 0; ty < kTilesY; ty++)
        for (int tx = 0; tx < kTilesX; tx++)
            if (dirty[ty][tx])
                ntiles++;

    esp_err_t err = ESP_OK;
    // kRot == 0 only: the pack below is a straight row copy with 2x expansion,
    // which is the identity mapping.  A rotated build keeps the band path, where
    // rot_map() handles each pixel.
    if (s_frame_buf != nullptr && kRot == 0 && ntiles >= kWholeWindowTiles) {
        // Whole window, one queued transfer.  The source is fb[] itself, so the
        // tiles that did NOT change are packed too - they have to be, the panel
        // window is the whole picture - but that costs a 32-bit store per two
        // output pixels and no extra DMA, because the DMA was already going to
        // be the whole window once this many tiles were dirty.
        const int64_t t_pack = esp_timer_get_time();
        uint8_t *dst = s_frame_buf;
        for (int gy = 0; gy < kWinH; gy++) {
            const uint16_t *src = fb + (kWinY + gy) * kFbPanel + kWinX;
            uint32_t *o = reinterpret_cast<uint32_t *>(dst);
            for (int x = 0; x < kWinW; x++) {
                const uint16_t c = src[x];
                const uint16_t sw = (uint16_t)((c >> 8) | (c << 8));   // RGB565 big endian
                o[x] = (uint32_t)sw | ((uint32_t)sw << 16);            // 2x horizontal
            }
            std::memcpy(dst + kRowBytes, dst, kRowBytes);              // 2x vertical
            dst += kRowBytes * kScale;
        }
        s_pack_us += uint32_t(esp_timer_get_time() - t_pack);
        s_rows_sent += uint32_t(kWinPxH);
        const int64_t t_blit = esp_timer_get_time();
        err = display_draw_bitmap_async(left_px(), top_px(), kWinPxW, kWinPxH, s_frame_buf);
        const int64_t dt_blit = esp_timer_get_time() - t_blit;
        if (dt_blit > s_blit_max_us)
            s_blit_max_us = uint32_t(dt_blit);
        s_blits++;
        s_blits_total++;
        s_win_pushes++;
    } else
    for (int ty = 0; ty < kTilesY && err == ESP_OK; ty++) {
        int bminx = kTilesX, bmaxx = -1;
        for (int tx = 0; tx < kTilesX; tx++) {
            if (!dirty[ty][tx]) continue;
            if (tx < bminx) bminx = tx;
            bmaxx = tx;
        }
        if (bmaxx < 0) continue;

        const int wpx = (bmaxx - bminx + 1) * kTile;
        const int rowb = wpx * kScale * 2;
        const int outx = left_px() + bminx * kTile * kScale;
        const int outy = top_px() + ty * kTile * kScale;

        for (int r = 0; r < kTile; r++) {
            const uint16_t *src = fb + (kWinY + ty * kTile + r) * kFbPanel + kWinX + bminx * kTile;
            for (int dy = 0; dy < kScale; dy++) {
                uint8_t *dst = s_strip + (r * kScale + dy) * rowb;
                if (kRot == 0) {
                    for (int x = 0; x < wpx; x++) {
                        const uint16_t c = src[x];
                        const uint16_t sw = (uint16_t)((c >> 8) | (c << 8));   // RGB565 big endian
                        const uint32_t pair = (uint32_t)sw | ((uint32_t)sw << 16);
                        *reinterpret_cast<uint32_t *>(dst + x * 4) = pair;
                    }
                } else {
                    for (int i = 0; i < wpx * kScale; i++) {
                        int sx, sy;
                        rot_map(bminx * kTile + (i >> 1), ty * kTile + r, &sx, &sy);
                        const uint16_t c = fb[(kWinY + sy) * kFbPanel + (kWinX + sx)];
                        dst[i * 2] = uint8_t(c >> 8);
                        dst[i * 2 + 1] = uint8_t(c & 0xff);
                    }
                }
            }
        }
        s_rows_sent += uint32_t(kTile * kScale);
        const int64_t t_blit = esp_timer_get_time();
        err = display_draw_bitmap(outx, outy, wpx * kScale, kTile * kScale, s_strip);
        const int64_t dt_blit = esp_timer_get_time() - t_blit;
        if (dt_blit > s_blit_max_us)
            s_blit_max_us = uint32_t(dt_blit);
        s_blits++;
        s_blits_total++;
    }
    if (err == ESP_OK) {
        s_have_prev = true;
        // Advance the repair sweep only after its band actually reached the
        // panel; a failed transfer keeps the index so the same band is retried.
        if (s_repair_ty >= 0 && ++s_repair_ty >= kTilesY)
            s_repair_ty = -1;
        // Everything marked dirty has now been pushed (the bands above cover
        // every set bit), so the map restarts empty.  A failed transfer leaves
        // the bits set and the next frame retries the same tiles.
        s_soc.lcd.dirty_clear();
    } else {
        s_have_prev = false;
        s_blit_errs++;
        static bool warned = false;
        if (!warned) {
            warned = true;
            ESP_LOGE(TAG, "display_draw_bitmap failed in band blit");
        }
    }
}

