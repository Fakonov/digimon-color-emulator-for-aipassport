#!/usr/bin/env python
"""Generate emu/hotblock.h from the validated recomp/hot_func.c.

The recomp generator targeted a libretro-style ``State`` whose RAM is an
inline array. The emulator needs the same code to operate directly on the SoC
RAM (so no 8 KiB copy per call) and to stop one instruction early, leaving the
trailing ``pop bp, pc`` to the interpreter so the return path keeps its exact
semantics.

Result: ``HotState`` with ``uint16_t *ram`` plus ``hot_block_prng()`` covering
0x2002F4..0x200342 and the measured cost of that range.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "recomp", "hot_func.c")
DST = os.path.join(ROOT, "emu", "hotblock.h")

HEADER = """/* AUTO-GENERATED by tools/gen_hotblock.py from recomp/hot_func.c. Do not edit. */
#ifndef HOTBLOCK_H
#define HOTBLOCK_H

#include <stdint.h>

/* Same layout as the validated PoC State, but RAM is a pointer so the block
   runs against the live SoC memory instead of a private copy. */
typedef struct {
    uint32_t r[8];
    uint16_t sb;
    uint16_t *ram;
} HotState;

#define UNSP_N 0x0200u
#define UNSP_Z 0x0100u
#define UNSP_S 0x0080u
#define UNSP_C 0x0040u

/* Instruction cost of 0x2002F4..0x200342, summed from the modal per-PC charge
   measured with --trace-cycles against MAME (dbgtest/cyc900.txt). */
#define HOT_BLOCK_CYCLES %(cycles)du
#define HOT_BLOCK_LAST   0x200342u

static inline uint16_t hot_ds(const HotState *s) { return (uint16_t)((s->r[6] >> 10) & 0x3f); }

static inline void hot_set_ds(HotState *s, uint16_t ds) {
    s->r[6] = (uint16_t)((s->r[6] & 0x03ffu) | ((ds & 0x3fu) << 10));
}

static inline uint16_t hot_read16(HotState *s, uint32_t addr) { return s->ram[addr & 0x0fffu]; }

static inline void hot_write16(HotState *s, uint32_t addr, uint16_t value) { s->ram[addr & 0x0fffu] = value; }

static inline void hot_update_nzsc(HotState *s, uint32_t value, uint16_t a, uint16_t b) {
    uint32_t f = s->r[6] & (uint16_t)~(UNSP_N | UNSP_Z | UNSP_S | UNSP_C);
    f |= (((value >> 16) ^ ((a ^ b) >> 15)) & 1u) << 7;
    f |= ((value >> 15) & 1u) << 9;
    f |= (uint32_t)((uint16_t)value == 0) << 8;
    f |= ((value >> 16) & 1u) << 6;
    s->r[6] = f;
}

static inline void hot_update_nz(HotState *s, uint32_t value) {
    uint32_t f = s->r[6] & (uint16_t)~(UNSP_N | UNSP_Z);
    f |= ((value >> 15) & 1u) << 9;
    f |= (uint32_t)((uint16_t)value == 0) << 8;
    s->r[6] = f;
}

"""

HELPERS = """
/* Kept 1:1 with recomp/unsp_state.h so the block's semantics stay identical to
   the version that passed the golden RAM comparison on real hardware. */
static inline void op_push(HotState *s, int reg) {
    hot_write16(s, s->r[0] & 0xffffu, (uint16_t)s->r[reg]);
    s->r[0] = (uint16_t)(s->r[0] - 1);
}

static inline void op_add_imm6(HotState *s, int rd, uint16_t imm) {
    uint32_t value = (uint32_t)(uint16_t)s->r[rd] + imm;
    hot_update_nzsc(s, value, (uint16_t)s->r[rd], imm);
    s->r[rd] = (uint16_t)value;
}

static inline void op_sub_imm6(HotState *s, int rd, uint16_t imm) {
    uint16_t n = (uint16_t)~imm;
    uint32_t value = (uint32_t)(uint16_t)s->r[rd] + n + 1u;
    hot_update_nzsc(s, value, (uint16_t)s->r[rd], n);
    s->r[rd] = (uint16_t)value;
}

static inline void op_bp_from_sp_imm16(HotState *s, uint16_t imm) {
    uint32_t value = (uint32_t)(uint16_t)s->r[0] + imm;
    hot_update_nzsc(s, value, (uint16_t)s->r[0], imm);
    s->r[5] = (uint16_t)value;
}

static inline void op_ld_imm16(HotState *s, int rd, uint16_t imm) {
    s->r[rd] = imm;
    hot_update_nz(s, imm);
}

static inline void op_ld_ind(HotState *s, int rd, int rs) {
    uint32_t ea = (uint32_t)(uint16_t)s->r[rs] | ((uint32_t)hot_ds(s) << 16);
    uint16_t value = hot_read16(s, ea);
    s->r[rd] = value;
    hot_update_nz(s, value);
}

static inline void op_ld_ind_postinc(HotState *s, int rd, int rs) {
    uint32_t ea = (uint32_t)(uint16_t)s->r[rs] | ((uint32_t)hot_ds(s) << 16);
    uint16_t value = hot_read16(s, ea);
    s->r[rs] = (uint16_t)(s->r[rs] + 1);
    s->r[rd] = value;
    hot_update_nz(s, value);
}

static inline void op_st_ind(HotState *s, int rs, int src) {
    uint32_t ea = (uint32_t)(uint16_t)s->r[rs] | ((uint32_t)hot_ds(s) << 16);
    hot_write16(s, ea, (uint16_t)s->r[src]);
}

static inline void op_st_ind_postinc(HotState *s, int rs, int src) {
    uint32_t ea = (uint32_t)(uint16_t)s->r[rs] | ((uint32_t)hot_ds(s) << 16);
    hot_write16(s, ea, (uint16_t)s->r[src]);
    s->r[rs] = (uint16_t)(s->r[rs] + 1);
}

static inline void op_ld_bp_imm(HotState *s, int rd, uint16_t off) {
    uint16_t value = hot_read16(s, (uint16_t)(s->r[5] + off));
    s->r[rd] = value;
    hot_update_nz(s, value);
}

static inline void op_st_bp_imm(HotState *s, int src, uint16_t off) {
    hot_write16(s, (uint16_t)(s->r[5] + off), (uint16_t)s->r[src]);
}

static inline void op_xor_ind(HotState *s, int rd, int rs) {
    uint32_t ea = (uint32_t)(uint16_t)s->r[rs] | ((uint32_t)hot_ds(s) << 16);
    uint16_t value = hot_read16(s, ea);
    s->r[rd] ^= value;
    hot_update_nz(s, s->r[rd]);
}

static inline void op_xor_ind_postinc(HotState *s, int rd, int rs) {
    uint16_t lhs = (uint16_t)s->r[rd];
    uint32_t ea = (uint32_t)(uint16_t)s->r[rs] | ((uint32_t)hot_ds(s) << 16);
    uint16_t value = hot_read16(s, ea);
    s->r[rs] = (uint16_t)(s->r[rs] + 1);
    s->r[rd] = (uint16_t)(lhs ^ value);
    hot_update_nz(s, s->r[rd]);
}

static inline void op_xor_bp_imm(HotState *s, int rd, uint16_t off) {
    uint16_t value = hot_read16(s, (uint16_t)(s->r[5] + off));
    s->r[rd] ^= value;
    hot_update_nz(s, s->r[rd]);
}

static inline void op_xor_reg(HotState *s, int rd, int rs) {
    s->r[rd] ^= s->r[rs];
    hot_update_nz(s, s->r[rd]);
}

static inline void op_lsl_reg(HotState *s, int rd, int rs) {
    s->r[rd] = (uint16_t)((uint16_t)s->r[rd] << (s->r[rs] & 0x1f));
}

static inline void op_lslor_reg(HotState *s, int rd, int rs) {
    uint32_t value = (uint32_t)(uint16_t)s->r[rd] << (s->r[rs] & 0x1f);
    s->r[3] = (uint16_t)value;
    s->r[4] = (uint16_t)(s->r[4] | (value >> 16));
}

static inline void op_shift_right_imm(HotState *s, int rd, int rs, int opn) {
    uint32_t shift = ((uint32_t)(uint16_t)s->r[rs] << 4) | s->sb;
    shift >>= (opn - 3);
    s->sb = (uint16_t)(shift & 0x0f);
    s->r[rd] = (uint16_t)(shift >> 4);
    hot_update_nz(s, s->r[rd]);
}

static inline void op_rotate_right_imm(HotState *s, int rd, int rs, int opn) {
    uint32_t shift = (((uint32_t)s->sb << 16) | (uint16_t)s->r[rs]) << 4 | s->sb;
    if (opn & 4) {
        shift >>= (opn - 3);
        s->sb = (uint16_t)(shift & 0x0f);
    } else {
        shift <<= (opn + 1);
        s->sb = (uint16_t)((shift >> 20) & 0x0f);
    }
    s->r[rd] = (uint16_t)(shift >> 4);
    hot_update_nz(s, s->r[rd]);
}

static inline void op_test_ind_postinc(HotState *s, int rd, int rs) {
    uint32_t ea = (uint32_t)(uint16_t)s->r[rs] | ((uint32_t)hot_ds(s) << 16);
    uint16_t value = hot_read16(s, ea);
    s->r[rs] = (uint16_t)(s->r[rs] + 1);
    hot_update_nz(s, (uint16_t)((uint16_t)s->r[rd] & value));
}

static inline void op_nop(HotState *s) { (void)s; }

"""


def main():
    try:
        with open(SRC, encoding="utf-8") as fp:
            body = fp.read()
    except OSError as exc:
        sys.exit("cannot read %s: %s" % (SRC, exc))

    start = body.index("void hot_func(State *s) {")
    end = body.index("    /* 200343 ")
    block = body[start:end].rstrip()
    block = block[: block.rindex("}")].rstrip() if block.endswith("}") else block
    block += "\n}\n"
    block = block.replace("void hot_func(State *s) {", "static inline void hot_block_prng(HotState *s) {", 1)
    block = block.replace("s->r[7] = HOT_ENTRY;\n", "")
    block = block.replace("unsp_set_ds(s,", "hot_set_ds(s,")

    cycles = 263  # see the docstring: 0x2002F4..0x200342 modal costs
    text = HEADER % {"cycles": cycles} + HELPERS + "\n" + block + "\n#endif\n"
    with open(DST, "w", encoding="utf-8", newline="\n") as fp:
        fp.write(text)
    insns = block.count("op_") + block.count("hot_") + block.count("unsp_")
    print("wrote %s (%d bytes, %d helper calls, %d cycles)" % (DST, len(text), insns, cycles))
    return 0


if __name__ == "__main__":
    sys.exit(main())
