"""Build tools/dmc_assets.js: base64 PNGs for the icon glyphs, the panel
screenshots and the Ver.1 sprites, all inlined so dmc_web.html stays a
double-clickable single page (plus this one script file).

Sources (all checked in under tools/dmc_src/)
  icons  : cropped out of main.bin.png, a MAME 96x96 panel capture
  shots  : MAME 96x96 panel captures (see tools/mame_shots.lua for how they were taken)
  sprites: humulos.com DMC dot sprites (36x36 gif)

Regenerate with:  python tools/build_web_assets.py
"""
import base64
import io
import os

from PIL import Image

OUT_JS = 'tools/dmc_assets.js'
ICON_SCALE = 4
SHOT_SCALE = 4

ICON_BOXES = {
    'status': (1, 2, 25, 20),
    'food':   (25, 2, 49, 20),
    'train':  (49, 2, 73, 20),
    'battle': (73, 2, 96, 20),
    'clean':  (1, 76, 25, 96),
    'sleep':  (25, 76, 49, 96),
    'heal':   (49, 76, 73, 96),
    'call':   (73, 76, 96, 96),
}

SHOTS = {
    'main':      'tools/dmc_src/main.bin.png',
    'load':      'tools/dmc_src/load.png',
    'clock':     'tools/dmc_src/clock.png',
    'settings':  'tools/dmc_src/settings.png',
    'sleepmenu': 'tools/dmc_src/sleepmenu.png',
    'clockover': 'tools/dmc_src/clockover.png',
    'boot':      'tools/dmc_src/boot.png',
}

SPRITES = [
    'digitama_c1', 'bota', 'koro', 'agu', 'beta', 'grey', 'tyrano', 'devi',
    'mera', 'airdra', 'seadra', 'nume', 'metalgrey_vi', 'mame', 'monzae',
    'blitzgrey', 'banchomame', 'shinmonzae', 'omega_a',
]


def b64(img, fmt='PNG', **kw):
    buf = io.BytesIO()
    img.save(buf, fmt, **kw)
    return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()


def main():
    src = Image.open(SHOTS['main']).convert('RGB')
    icons = {}
    for name, box in ICON_BOXES.items():
        im = src.crop(box)
        im = im.resize((im.width * ICON_SCALE, im.height * ICON_SCALE), Image.NEAREST)
        icons[name] = b64(im)
        print('icon', name, im.size)

    shots = {}
    for name, path in SHOTS.items():
        im = Image.open(path).convert('RGB')
        im = im.resize((im.width * SHOT_SCALE, im.height * SHOT_SCALE), Image.NEAREST)
        shots[name] = b64(im)
        print('shot', name, im.size)

    sprites = {}
    for key in SPRITES:
        p = f'tools/dmc_src/sp_{key}.gif'
        im = Image.open(p).convert('RGBA')
        sprites[key] = b64(im)
        print('sprite', key, im.size)

    parts = [
        '// Generated by tmp/build_web_assets.py - do not edit by hand.',
        '// icons/shots: MAME 96x96 panel captures; sprites: humulos.com DMC dot sprites.',
        'const DMC_ASSETS = {',
        '  icons: {',
    ]
    for k, v in icons.items():
        parts.append(f'    {k}: "{v}",')
    parts.append('  },')
    parts.append('  shots: {')
    for k, v in shots.items():
        parts.append(f'    {k}: "{v}",')
    parts.append('  },')
    parts.append('  sprites: {')
    for k, v in sprites.items():
        parts.append(f'    {k}: "{v}",')
    parts.append('  },')
    parts.append('};')
    js = '\n'.join(parts) + '\n'
    open(OUT_JS, 'w', encoding='utf-8').write(js)
    print('wrote', OUT_JS, len(js), 'bytes')


if __name__ == '__main__':
    main()
