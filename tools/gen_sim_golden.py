#!/usr/bin/env python3
"""Generate C arrays for the ESP32-C3 recomp self-test.

Reads the MAME golden RAM snapshots from dbgtest/ and writes a header next to
the bench main.  The values are 16-bit little-endian words, exactly the layout
unsp_state.h expects.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "firmware" / "recomp-bench" / "main" / "golden_data.h"
FILES = {
    "GOLDEN_HOT_ENTRY": "entry_ram.bin",
    "GOLDEN_HOT_EXIT": "exit_ram.bin",
    "GOLDEN_HOT_ENTRY2": "entry2_ram.bin",
    "GOLDEN_HOT_EXIT2": "exit2_ram.bin",
    "GOLDEN_DELAY_ENTRY": "delay_entry_ram.bin",
    "GOLDEN_DELAY_EXIT": "delay_exit_ram.bin",
}

def words(path: pathlib.Path):
    data = path.read_bytes()
    if len(data) != 8192:
        raise SystemExit(f"{path}: expected 8192 B, got {len(data)}")
    return [data[i] | (data[i + 1] << 8) for i in range(0, len(data), 2)]

def emit(name, vals):
    lines = [f"static const uint16_t {name}[4096] = {{"]
    for i in range(0, 4096, 12):
        chunk = ", ".join(f"0x{v:04X}" for v in vals[i:i + 12])
        lines.append("    " + chunk + ",")
    lines.append("};")
    return "\n".join(lines)

def main():
    OUT.parent.mkdir(parents=True, exist_ok=True)
    parts = [
        "/* AUTO-GENERATED by tools/gen_sim_golden.py. Do not hand-edit. */",
        "#ifndef GOLDEN_DATA_H",
        "#define GOLDEN_DATA_H",
        "#include <stdint.h>",
        "",
    ]
    for name, filename in FILES.items():
        path = ROOT / "dbgtest" / filename
        parts.append(f"/* {filename} */")
        parts.append(emit(name, words(path)))
        parts.append("")
    parts += [
        "/* Register expectations captured at the MAME breakpoints. */",
        "#define HOT0_R0 0x0FF5u",
        "#define HOT0_R1 0x90F0u",
        "#define HOT0_R2 0x1F30u",
        "#define HOT0_R3 0xC08Du",
        "#define HOT0_R4 0x0601u",
        "#define HOT0_R5 0x0FF3u",
        "#define HOT0_R6 0x0020u",
        "#define HOT0_R7 0x200343u",
        "#define HOT0_SB 0x0001u",
        "",
        "#define HOT1_R0 0x0FF5u",
        "#define HOT1_R1 0xEE2Eu",
        "#define HOT1_R2 0xCB76u",
        "#define HOT1_R3 0x588Bu",
        "#define HOT1_R4 0x0601u",
        "#define HOT1_R5 0x0FF3u",
        "#define HOT1_R6 0x0020u",
        "#define HOT1_R7 0x200343u",
        "#define HOT1_SB 0x000Cu",
        "",
        "#define DELAY_R4 0x03E8u",
        "#define DELAY_R5 0x0FF5u",
        "#define DELAY_R6 0x0040u",
        "#define DELAY_R7 0x537Fu",
        "#define DELAY_SB 0x0000u",
        "",
        "#endif",
    ]
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"{OUT}  {OUT.stat().st_size} B  {len(OUT.read_text(encoding='utf-8').splitlines())} lines")

if __name__ == "__main__":
    main()
