#!/usr/bin/env python3
"""First static-recompilation unit for Digimon Color.

Reads the MAME disassembly of the hot function at 0x2002F4 and emits a
straight-line C function.  This is deliberately a narrow, trace-guided
translator: the lowering table covers exactly the instructions observed in
that block.  No runtime instruction fetch/decode/dispatch happens.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASM = ROOT / "dbgtest" / "hot.asm"
OUT = Path(__file__).resolve().parent / "hot_func.c"
STOP_PC = 0x200343

line_re = re.compile(r"^([0-9A-Fa-f]{6}):\s+([0-9A-Fa-f]{4})(?:\s+([0-9A-Fa-f]{4}))?\s+(.*)$")

def lower(pc, op, imm, text):
    opn = (op >> 3) & 7
    def r(n): return int(n)

    m = re.fullmatch(r"push bp, bp to \[sp\]", text)
    if m: return "op_push(s, 5);"
    m = re.fullmatch(r"sp -= ([0-9a-fA-F]+)", text)
    if m: return "op_sub_imm6(s, 0, 0x%s);" % m.group(1)
    m = re.fullmatch(r"sp \+= ([0-9a-fA-F]+)", text)
    if m: return "op_add_imm6(s, 0, 0x%s);" % m.group(1)
    m = re.fullmatch(r"bp = sp \+ ([0-9a-fA-F]+)", text)
    if m: return "op_bp_from_sp_imm16(s, 0x%s);" % m.group(1)
    m = re.fullmatch(r"ds = ([0-9a-fA-F]+)", text)
    if m: return "unsp_set_ds(s, 0x%s);" % m.group(1)
    m = re.fullmatch(r"r(\d) = ds:\[r(\d)\+\+\]", text)
    if m: return "op_ld_ind_postinc(s, %s, %s);" % (m.group(1), m.group(2))
    m = re.fullmatch(r"r(\d) = ds:\[r(\d)\]", text)
    if m: return "op_ld_ind(s, %s, %s);" % (m.group(1), m.group(2))
    m = re.fullmatch(r"r(\d) = r(\d) lsl r(\d)", text)
    if m: return "op_lsl_reg(s, %s, %s);" % (m.group(1), m.group(3))
    m = re.fullmatch(r"r(\d) = r(\d) lslor r(\d)", text)
    if m: return "op_lslor_reg(s, %s, %s);" % (m.group(1), m.group(3))
    m = re.fullmatch(r"r(\d) \^= ds:\[r(\d)\+\+\]", text)
    if m: return "op_xor_ind_postinc(s, %s, %s);" % (m.group(1), m.group(2))
    m = re.fullmatch(r"r(\d) \^= ds:\[r(\d)\]", text)
    if m: return "op_xor_ind(s, %s, %s);" % (m.group(1), m.group(2))
    m = re.fullmatch(r"\[bp\+([0-9a-fA-F]+)\] = r(\d)", text)
    if m: return "op_st_bp_imm(s, %s, 0x%s);" % (m.group(2), m.group(1))
    m = re.fullmatch(r"ds:\[r(\d)\+\+\] = r(\d)", text)
    if m: return "op_st_ind_postinc(s, %s, %s);" % (m.group(1), m.group(2))
    m = re.fullmatch(r"ds:\[r(\d)\] = r(\d)", text)
    if m: return "op_st_ind(s, %s, %s);" % (m.group(1), m.group(2))
    m = re.fullmatch(r"r(\d) = \[bp\+([0-9a-fA-F]+)\]", text)
    if m: return "op_ld_bp_imm(s, %s, 0x%s);" % (m.group(1), m.group(2))
    m = re.fullmatch(r"r(\d) = r(\d) lsr ([0-9a-fA-F]+)", text)
    if m:
        if int(m.group(3), 16) != opn - 3:
            raise SystemExit("shift amount mismatch at %04X: %s" % (pc, text))
        return "op_shift_right_imm(s, %s, %s, %d);" % (m.group(1), m.group(2), opn)
    m = re.fullmatch(r"r(\d) = r(\d) ror ([0-9a-fA-F]+)", text)
    if m:
        if int(m.group(3), 16) != opn - 3:
            raise SystemExit("rotate amount mismatch at %04X: %s" % (pc, text))
        return "op_rotate_right_imm(s, %s, %s, %d);" % (m.group(1), m.group(2), opn)
    m = re.fullmatch(r"r(\d) \^= \[bp\+([0-9a-fA-F]+)\]", text)
    if m: return "op_xor_bp_imm(s, %s, 0x%s);" % (m.group(1), m.group(2))
    m = re.fullmatch(r"r(\d) \^= r(\d)", text)
    if m: return "op_xor_reg(s, %s, %s);" % (m.group(1), m.group(2))
    m = re.fullmatch(r"test r(\d), ds:\[r(\d)\+\+\]", text)
    if m: return "op_test_ind_postinc(s, %s, %s);" % (m.group(1), m.group(2))
    m = re.fullmatch(r"pop bp, pc from \[sp\]", text)
    if m: return "op_ret(s);"
    m = re.fullmatch(r"r(\d) = ([0-9a-fA-F]+)", text)
    if m:
        val = imm if imm is not None else int(m.group(2), 16)
        return "op_ld_imm16(s, %s, 0x%04X);" % (m.group(1), val)
    raise SystemExit("no lowering for %04X %04X: %s" % (pc, op, text))

def main():
    body = []
    count = 0
    with ASM.open("r", encoding="utf-8") as f:
        for raw in f:
            raw = raw.rstrip("\n")
            m = line_re.match(raw)
            if not m:
                continue
            pc = int(m.group(1), 16)
            op = int(m.group(2), 16)
            imm = int(m.group(3), 16) if m.group(3) else None
            text = m.group(4).strip()
            stmt = lower(pc, op, imm, text)
            body.append("    /* %04X %04X  %s */" % (pc, op, text))
            body.append("    " + stmt)
            count += 1
            if pc == STOP_PC:
                break
    if not body or "op_ret(s);" not in body[-1]:
        raise SystemExit("did not stop at return: %r" % body[-3:])
    out = []
    out.append("/* AUTO-GENERATED by recomp/gen_recomp.py from dbgtest/hot.asm. */")
    out.append("/* Trace-guided static translation of 0x2002F4..0x200343. */")
    out.append('#include "unsp_state.h"')
    out.append("")
    out.append("#define HOT_ENTRY 0x2002F4u")
    out.append("#define HOT_EXIT  0x200343u")
    out.append("#define HOT_GUEST_INSNS %du" % count)
    out.append("")
    out.append("void hot_func(State *s) {")
    out.append("    s->r[7] = HOT_ENTRY;")
    out.extend(body)
    out.append("}")
    out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8")
    print("wrote", OUT, "instructions", count)

if __name__ == "__main__":
    main()
