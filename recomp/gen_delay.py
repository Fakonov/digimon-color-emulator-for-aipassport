#!/usr/bin/env python3
"""Static translation of the 0x5376..0x537E delay loop.

This is the second unit: it exercises a real conditional branch and a backward
jump.  The input is MAME's disassembly (opcode + mnemonic); the output is C
with labels, not a runtime decoder.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASM = ROOT / "dbgtest" / "delay.asm"
OUT = Path(__file__).resolve().parent / "delay_func.c"

line_re = re.compile(r"^([0-9A-Fa-f]{6}):\s+([0-9A-Fa-f]{4})(?:\s+([0-9A-Fa-f]{4}))?\s+(.*)$")

def lower(pc, op, imm, text):
    m = re.fullmatch(r"r(\d) = \[bp\+([0-9a-fA-F]+)\]", text)
    if m: return "op_ld_bp_imm(s, %s, 0x%s);" % (m.group(1), m.group(2))
    m = re.fullmatch(r"cmp r(\d), ([0-9a-fA-F]+)", text)
    if m:
        val = imm if imm is not None else int(m.group(2), 16)
        return "op_cmp_imm16(s, %s, 0x%04X);" % (m.group(1), val)
    m = re.fullmatch(r"ja ([0-9a-fA-F]+)", text)
    if m: return "if (op_ja(s)) { s->r[7] = 0x%su; goto L_%s; }" % (m.group(1).upper(), m.group(1).upper())
    m = re.fullmatch(r"nop", text)
    if m: return "op_nop(s);"
    m = re.fullmatch(r"r(\d) \+= ([0-9a-fA-F]+)", text)
    if m: return "op_add_imm6(s, %s, 0x%s);" % (m.group(1), m.group(2))
    m = re.fullmatch(r"\[bp\+([0-9a-fA-F]+)\] = r(\d)", text)
    if m: return "op_st_bp_imm(s, %s, 0x%s);" % (m.group(2), m.group(1))
    m = re.fullmatch(r"jmp ([0-9a-fA-F]+)", text)
    if m: return "s->r[7] = 0x%su; goto L_%s;" % (m.group(1).upper(), m.group(1).upper())
    raise SystemExit("no lowering for %04X %04X: %s" % (pc, op, text))

def main():
    rows = []
    with ASM.open("r", encoding="utf-8") as f:
        for raw in f:
            m = line_re.match(raw.rstrip("\n"))
            if m:
                rows.append((int(m.group(1), 16), int(m.group(2), 16),
                             int(m.group(3), 16) if m.group(3) else None,
                             m.group(4).strip()))
    # keep the loop body only: entry 5376 through the exit target 537F
    rows = [r for r in rows if 0x5376 <= r[0] <= 0x537F]
    if not rows or rows[0][0] != 0x5376 or rows[-1][0] != 0x537F:
        raise SystemExit("unexpected delay.asm boundaries: %r" % (rows[0][0], rows[-1][0]))

    body = []
    count = 0
    for pc, op, imm, text in rows:
        if pc == 0x537F:
            body.append("L_537F:")
            body.append("    s->r[7] = DELAY_EXIT;")
            continue
        body.append("    /* %04X %04X  %s */" % (pc, op, text))
        body.append("    " + lower(pc, op, imm, text))
        count += 1
        if pc == 0x5376:
            body.insert(len(body) - 2, "L_5376:")

    out = []
    out.append("/* AUTO-GENERATED by recomp/gen_delay.py from dbgtest/delay.asm. */")
    out.append("/* Static translation of the conditional delay loop 0x5376..0x537E. */")
    out.append('#include "unsp_state.h"')
    out.append("")
    out.append("#define DELAY_ENTRY 0x5376u")
    out.append("#define DELAY_EXIT  0x537Fu")
    out.append("#define DELAY_GUEST_INSNS 8003u")
    out.append("")
    out.append("void delay_loop(State *s) {")
    out.append("    s->r[7] = DELAY_ENTRY;")
    out.extend(body)
    out.append("}")
    out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8")
    print("wrote", OUT, "body instructions", count)

if __name__ == "__main__":
    main()
