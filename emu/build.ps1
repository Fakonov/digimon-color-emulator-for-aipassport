# Build the PC-side reference emulator (w64devkit g++).
#   .\emu\build.ps1            build emu/digicore.exe
#   .\emu\build.ps1 -Test     also build+run emu/link_test.exe
param([switch]$Test)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
Set-Location $root

$g = "C:\Users\DuWeisi\w64devkit\bin\g++.exe"
$cxxflags = @("-std=c++20", "-O2", "-Wall", "-Wextra", "-Wno-unused-parameter", "-Wno-unused-variable",
              "-Wno-unused-but-set-variable", "-Wno-sign-compare", "-Wno-missing-field-initializers",
              "-I", "emu/compat", "-I", "emu")

# The ISA files are copied from ref/unsp so that "unsp.h" resolves to emu/compat,
# then compiled as one translation unit together with the dispatch glue
# (emu/isa/unsp_amalgam.cpp): the interpreter's call chain is only inlinable
# when execute_one and execute_remaining share a unit.
New-Item -ItemType Directory -Force emu/isa, emu/obj | Out-Null
$isa = @("unsp_other", "unsp_fxxx", "unsp_exxx", "unsp_extended", "unsp_jumps")
foreach ($f in $isa) {
    Copy-Item "ref/unsp/$f.cpp" "emu/isa/$f.cpp" -Force
}

$objs = @()
$o = "emu/obj/isa_amalgam.o"
& $g @cxxflags -c -o $o "emu/isa/unsp_amalgam.cpp"
if ($LASTEXITCODE -ne 0) { throw "compile failed: unsp_amalgam" }
$objs += $o

# AOT block table (generated by tools/aot.py from the interpreter hot blocks).
if (Test-Path "emu/aot_blocks.c") {
    $o = "emu/obj/aot_blocks.o"
    & $g @cxxflags -c -o $o "emu/aot_blocks.c"
    if ($LASTEXITCODE -ne 0) { throw "compile failed: aot_blocks" }
    $objs += $o
}

foreach ($f in @("gpce4", "st7735", "audio_dump", "main")) {
    if (-not (Test-Path "emu/$f.cpp")) { continue }
    $o = "emu/obj/$f.o"
    & $g @cxxflags -c -o $o "emu/$f.cpp"
    if ($LASTEXITCODE -ne 0) { throw "compile failed: $f" }
    $objs += $o
}

if (Test-Path "emu/main.cpp") {
    & $g -o emu/digicore.exe @objs
    if ($LASTEXITCODE -ne 0) { throw "link failed" }
    Write-Host "built emu/digicore.exe"
}

# Interactive player: same objects minus main.o, plus the Win32/GDI front end.
if (Test-Path "emu/player.cpp") {
    $po = "emu/obj/player.o"
    & $g @cxxflags -c -o $po "emu/player.cpp"
    if ($LASTEXITCODE -ne 0) { throw "compile failed: player" }
    $playerobjs = ($objs | Where-Object { $_ -notmatch "main\.o$" }) + $po
    & $g -o emu/digimon-player.exe @playerobjs -mwindows -lgdi32
    if ($LASTEXITCODE -ne 0) { throw "player link failed" }
    Write-Host "built emu/digimon-player.exe"
}

if ($Test) {
    & $g @cxxflags -o emu/link_test.exe emu/link_test.cpp ($objs | Where-Object { $_ -notmatch "main\.o$" })
    if ($LASTEXITCODE -ne 0) { throw "link_test link failed" }
    & emu/link_test.exe
}
